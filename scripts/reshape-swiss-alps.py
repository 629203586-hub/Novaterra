"""Build a reproducible, continuous Alpine heightfield and its exact ski sampler."""
from pathlib import Path
import json, math, re

page = Path(__file__).resolve().parents[1] / 'dist' / 'switzerland.html'
html = page.read_text()
nx, nz = 84, 50
x0, x1, z0, z1 = -21, 21, -17, -4.5

def smooth(v):
    v = max(0, min(1, v))
    return v*v*(3-2*v)

def elevation(x, z):
    peaks = [(-11,-12.5,8.5,4.3,13.0),(-5.4,-13.0,6.8,4.3,12.6),(5.3,-12.8,7.6,4.1,11.2),(14.6,-11.7,6.0,4.0,8.5)]
    masses = [h*math.exp(-((x-px)/sx)**2-((z-pz)/sz)**2) for px,pz,sx,sz,h in peaks]
    ridge = max(masses)
    grain = (.22*math.sin(x*.80+z*.67)+.13*math.sin(x*1.65-z*.91)) * min(1,ridge/8)
    ridge = max(0,ridge+grain)*smooth((-4.5-z)/4.2)
    shoulder = 8.9*math.exp(-(max(0,abs(x-5.25)-1.1)/4.2)**2-(max(0,abs(z+6.7)-.8)/2.8)**2)*smooth((-4.5-z)/.9)
    height = max(ridge,shoulder)*smooth((z+17)/2.2)*smooth((21-abs(x))/2.0)
    # Level village foundations and blend their clearings into the foothills.
    for bx,bz,w,d in [(-13,-5,3.4,2.7),(-17.9,-6,2.6,2.4),(17.4,-5.4,2.8,2.3)]:
        distance=max(abs(x-bx)-w/2-.4,abs(z-bz)-d/2-.4)
        height *= smooth(distance/1.25)
    return round(.84+height,3)

vertices = []
for j in range(nz+1):
    z = z0+(z1-z0)*j/nz
    for i in range(nx+1):
        x = x0+(x1-x0)*i/nx
        vertices.append([round(x,4),elevation(x,z),round(z,4)])

bins = [[],[],[],[]]
for j in range(nz):
    for i in range(nx):
        a=j*(nx+1)+i; b=a+1; c=a+nx+1; d=c+1
        faces=[(a,c,b),(b,c,d)] if (i+j)%2==0 else [(a,c,d),(a,d,b)]
        for face in faces:
            pts=[vertices[k] for k in face]
            x,y,z=[sum(p[k] for p in pts)/3 for k in range(3)]
            u=max(0,min(1,(z+11)/6.75))
            center=-9.25+1.65*u+.12*math.sin(u*math.pi*4)
            piste=-11.1<z<-4.5 and abs(x-center)<1.15
            snowline=7.5+.65*math.sin(x*.44+z*.17)+.3*math.sin(x*.95-z*.49)
            dx=[pts[1][k]-pts[0][k] for k in range(3)]
            dz=[pts[2][k]-pts[0][k] for k in range(3)]
            normal=[dx[1]*dz[2]-dx[2]*dz[1],dx[2]*dz[0]-dx[0]*dz[2],dx[0]*dz[1]-dx[1]*dz[0]]
            length=math.sqrt(sum(v*v for v in normal)) or 1
            slope=1-abs(normal[1])/length
            rib=math.sin(x*.85+z*.42)>.76 and slope>.25 and y<snowline+2
            if piste: mat=2
            elif y>snowline and not rib: mat=3 if normal[0]/length>.2 else 2
            else: mat=1 if normal[0]/length>.25 else 0
            bins[mat].extend(v for p in pts for v in p)

html=re.sub(r'const alpineRidgeMeshes=\[.*?\];',lambda m:'const alpineRidgeMeshes='+json.dumps(bins,separators=(',',':'))+';',html,count=1)
html=re.sub(r'const ridgeHeights=\[.*?\];',lambda m:'const ridgeHeights='+json.dumps([p[1] for p in vertices],separators=(',',':'))+';',html,count=1)
sampler="function ridgeHeight(x,z){if(x < -21 || x > 21 || z < -17 || z > -4.5)return .84;const u=THREE.MathUtils.clamp((x+21)/42*84,0,83.999999),v=THREE.MathUtils.clamp((z+17)/12.5*50,0,49.999999),i=Math.floor(u),j=Math.floor(v),a=u-i,b=v-j,k=j*85+i,A=ridgeHeights[k],B=ridgeHeights[k+1],C=ridgeHeights[k+85],D=ridgeHeights[k+86];if((i+j)%2===0)return a+b<=1?A+(B-A)*a+(C-A)*b:D+(C-D)*(1-a)+(B-D)*(1-b);return b>=a?A+(D-C)*a+(C-A)*b:A+(B-A)*a+(D-B)*b;}"
html=re.sub(r'function ridgeHeight[^\n]+',lambda m:sampler,html,count=1)
html=html.replace('// An alpine ridge sculpted procedurally in Blender: one continuous, faceted mountain landscape.','// Broad connected Alpine ridges; generated by scripts/reshape-swiss-alps.py.')
html=html.replace('// Alpine skiers follow the front slope of the Blender-sculpted Matterhorn.','// Alpine skiers follow the exact triangles of the rounded mountain piste.')
marker = '// The cableway terrace sits on a broad shoulder beside the main snow peaks.'
if marker not in html: marker = '// The upper station stands on an integrated Alpine shoulder, with a stone terrace.'
start=html.index(marker)
end=html.index('\nfor(let i=0;i<22;i++)',start)
html=html[:start]+'''// The upper station stands on an integrated Alpine shoulder, with a stone terrace.
box(M.stone,5.25,9.75,-6.7,4.6,.4,3.1);for(const dx of[-1.95,1.95])for(const dz of[-1.15,1.15]){const x=5.25+dx,z=-6.7+dz,h=ridgeHeight(x,z);if(h<9.6)box(M.stone,x,(h+9.65)/2,z,.32,9.65-h,.32);}'''+html[end:]
page.write_text(html)
print('Alpine terrain:',len(vertices),'vertices;',sum(len(b)//9 for b in bins),'triangles; peak',max(p[1] for p in vertices))
